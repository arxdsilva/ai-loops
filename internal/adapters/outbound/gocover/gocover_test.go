type gateDiff = gate.Diff

// goPacks is the reference Go pack detected at root.
func goPacks(t *testing.T, root string) []langpack.Detected {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("..", "..", "..", "..", "specs", "languages", "go", "pack.json"))
	if err != nil {
		t.Fatal(err)
	}
	p, err := pack.Parse(b)
	if err != nil {
		t.Fatal(err)
	}
	return []langpack.Detected{{Pack: p, ID: p.ID, Name: p.Name, Root: root}}
}

func needGit(t *testing.T) {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("no git")
	}
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
}

func git(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", "-c", "init.defaultBranch=main"}, args...)...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v: %s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func write(t *testing.T, dir, name, data string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

func commitAll(t *testing.T, dir, msg string) {
	t.Helper()
	git(t, dir, "add", "-A")
	git(t, dir, "commit", "-q", "-m", msg)
}

const (
	aGo     = "package a\n\nfunc F(x int) int {\n\tif x > 0 {\n\t\treturn 1\n\t}\n\treturn 2\n}\n"
	aTestGo = "package a\n\nimport \"testing\"\n\nfunc TestF(t *testing.T) {\n\tif F(1) != 1 || F(0) != 2 {\n\t\tt.Fatal(\"F\")\n\t}\n}\n"
	newGo   = "package a\n\nfunc G(x int) int {\n\tif x > 0 {\n\t\treturn x * 2\n\t}\n\treturn -x\n}\n"
	newTest = "package a\n\nimport \"testing\"\n\nfunc TestG(t *testing.T) {\n\tif G(2) != 4 || G(-1) != 1 {\n\t\tt.Fatal(\"G\")\n\t}\n}\n"
	genGo   = "// Code generated by hand-gen. DO NOT EDIT.\n\npackage a\n\nfunc H(x int) int {\n\tif x > 0 {\n\t\treturn 3\n\t}\n\treturn 4\n}\n"
	bGo     = "package b\n\nfunc B(x int) int {\n\tif x > 0 {\n\t\treturn 5\n\t}\n\treturn 6\n}\n"
)

// tinyModule creates a git repo holding a tested module, committed on main.
func tinyModule(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	git(t, dir, "init", "-q")
	write(t, dir, "go.mod", "module example.com/tiny\n\ngo 1.22\n")
	write(t, dir, "a/a.go", aGo)
	write(t, dir, "a/a_test.go", aTestGo)
	commitAll(t, dir, "base")
	return dir
}

type noRec struct{}

func (noRec) Record(context.Context, run.Event) error { return nil }

type clock struct{}

func (clock) Now() time.Time { return time.Time{} }

// gateCoverage runs `loops gate --only test,coverage` against dir.
func gateCoverage(t *testing.T, dir string) gate.CheckResult {
	t.Helper()
	t.Setenv("GOWORK", "off")
	t.Setenv("GOFLAGS", "")
	s := gate.New(gotool.New(), nil, noRec{}, clock{}).WithCoverage(New(), gate.CoverageConfig{})
	res, err := s.Run(context.Background(), gate.Options{
		Root: dir, Only: []string{gate.CheckTest, gate.CheckCoverage}, Packs: goPacks(t, "."),
		CoverProfile: filepath.Join(t.TempDir(), "cover.out"), Base: "main",
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range res.Checks {
		if c.Name == gate.CheckTest && !c.OK {
			t.Fatalf("test failed: %s", c.Output)
		}
	}
	return res.Checks[6]
}

func TestGateEndToEnd(t *testing.T) {
	needGit(t)
	if testing.Short() {
		t.Skip("runs go test")
	}
	dir := tinyModule(t)
	git(t, dir, "checkout", "-q", "-b", "feature")

	// A new, untracked, untested file fails.
	write(t, dir, "a/new.go", newGo)
	c := gateCoverage(t, dir)
	if c.OK || !strings.Contains(c.Output, "a/new.go:4: new code in new.go is untested (0/") {
		t.Fatalf("untested new file passed:\n%s", c.Output)
	}

	// With its test it passes (the untracked test counts too).
	write(t, dir, "a/new_test.go", newTest)
	if c = gateCoverage(t, dir); !c.OK || !strings.Contains(c.Output, "a/new.go") {
		t.Fatalf("tested new file failed:\n%s", c.Output)
	}

	// A generated, untested file is ignored.
	write(t, dir, "a/gen.go", genGo)
	if c = gateCoverage(t, dir); !c.OK || strings.Contains(c.Output, "gen.go") {
		t.Fatalf("generated file judged:\n%s", c.Output)
	}

	// A committed new package without tests fails.
	write(t, dir, "b/b.go", bGo)
	commitAll(t, dir, "feature work")
	c = gateCoverage(t, dir)
	if c.OK || !strings.Contains(c.Output, "b/b.go:4: package b has no tests") {
		t.Fatalf("untested package passed:\n%s", c.Output)
	}
}

func TestDiffBases(t *testing.T) {
	needGit(t)
	ctx := context.Background()
	r := New()

	// Not a git repo: whole-package mode.
	if d, err := r.Diff(ctx, t.TempDir(), ""); err != nil || !d.NoGit {
		t.Fatalf("%+v %v", d, err)
	}

	// No commits yet: the empty tree, untracked files listed.
	dir := t.TempDir()
	git(t, dir, "init", "-q")
	write(t, dir, "x/x.go", "package x\n")
	write(t, dir, "x/x_test.go", "package x\n")
	write(t, dir, "notes.txt", "n\n")
	d, err := r.Diff(ctx, dir, "")
	if err != nil || d.NoGit || d.Text != "" || !strings.HasPrefix(d.Base, "empty tree") || !reflect.DeepEqual(d.Untracked, []string{"x/x.go", "x/x_test.go"}) {
		t.Fatalf("%+v %v", d, err)
	}

	// One commit on a branch that is not main: still the empty tree.
	git(t, dir, "checkout", "-q", "-b", "trunk")
	commitAll(t, dir, "one")
	d, err = r.Diff(ctx, dir, "")
	if err != nil || !strings.Contains(d.Text, "+++ b/x/x.go") || len(d.Untracked) != 0 {
		t.Fatalf("%+v %v", d, err)
	}

	// Two commits, no main: HEAD~1.
	write(t, dir, "x/y.go", "package x\n\nvar Y = 1\n")
	commitAll(t, dir, "two")
	d, _ = r.Diff(ctx, dir, "")
	if !strings.Contains(d.Text, "+++ b/x/y.go") || strings.Contains(d.Text, "x/x.go") || d.Base != "HEAD~1 ("+git(t, dir, "rev-parse", "--short=12", "HEAD~1")+"; no default branch found)" {
		t.Fatalf("%+v", d)
	}

	// A main branch: merge-base with main.
	git(t, dir, "branch", "main", "HEAD~1")
	write(t, dir, "x/z.go", "package x\n")
	commitAll(t, dir, "three")
	d, _ = r.Diff(ctx, dir, "")
	if !strings.Contains(d.Text, "x/y.go") || !strings.Contains(d.Text, "x/z.go") || d.Base != "main (merge-base "+git(t, dir, "rev-parse", "--short=12", "main")+")" {
		t.Fatalf("%+v", d)
	}

	// origin/main wins over main.
	git(t, dir, "update-ref", "refs/remotes/origin/main", "HEAD~1")
	d, _ = r.Diff(ctx, dir, "")
	if strings.Contains(d.Text, "x/y.go") || !strings.Contains(d.Text, "x/z.go") || !strings.HasPrefix(d.Base, "origin/main (merge-base ") {
		t.Fatalf("%+v", d)
	}

	// Explicit base; unknown base is an error.
	d, err = r.Diff(ctx, dir, "main")
	if err != nil || !strings.HasPrefix(d.Base, "main (merge-base ") || !strings.Contains(d.Text, "x/y.go") {
		t.Fatalf("%+v %v", d, err)
	}
	if _, err := r.Diff(ctx, dir, "no-such-ref"); err == nil || !strings.Contains(err.Error(), "no-such-ref") {
		t.Fatal(err)
	}

	// A module in a subdirectory: paths are relative to it, others dropped.
	write(t, dir, "sub/go.mod", "module example.com/sub\n")
	write(t, dir, "sub/s/s.go", "package s\n")
	commitAll(t, dir, "four")
	d, _ = r.Diff(ctx, filepath.Join(dir, "sub"), "HEAD~1")
	if !strings.Contains(d.Text, "+++ b/s/s.go") || strings.Contains(d.Text, "x/") {
		t.Fatalf("%+v", d)
	}
}

func TestFilesAndModule(t *testing.T) {
	dir := t.TempDir()
	r := New()
	write(t, dir, "go.mod", "// comment\nmodule \"example.com/q\" // trailing\n\ngo 1.22\n")
	if m, err := r.Module(dir); err != nil || m != "example.com/q" {
		t.Fatalf("%q %v", m, err)
	}
	write(t, dir, "bad/go.mod", "go 1.22\n")
	if _, err := r.Module(filepath.Join(dir, "bad")); err == nil {
		t.Fatal("no module line accepted")
	}
	if _, err := r.Module(filepath.Join(dir, "missing")); err == nil {
		t.Fatal("missing go.mod accepted")
	}
	write(t, dir, "p/p.go", "package p\n")
	write(t, dir, "p/p_test.go", "package p\n")
	write(t, dir, "q/q.go", "package q\n")
	write(t, dir, "g/g.go", "// Code generated by x. DO NOT EDIT.\n\npackage g\n")
	write(t, dir, "rootfile.go", "package q\n")
	if !r.HasTests(dir, "p") || r.HasTests(dir, "q") || r.HasTests(dir, "missing") {
		t.Fatal("HasTests")
	}
	if !r.Generated(dir, "g/g.go") || r.Generated(dir, "q/q.go") || r.Generated(dir, "missing.go") {
		t.Fatal("Generated")
	}
	write(t, dir, "c.out", "mode: set\n")
	if s, err := r.Profile(filepath.Join(dir, "c.out")); err != nil || s != "mode: set\n" {
		t.Fatalf("%q %v", s, err)
	}
	if _, err := r.Profile(filepath.Join(dir, "none.out")); err == nil {
		t.Fatal("missing profile accepted")
	}
	link := filepath.Join(t.TempDir(), "link")
	if err := os.Symlink(filepath.Join(dir, "p"), link); err != nil {
		t.Skip(err)
	}
	want, _ := filepath.EvalSymlinks(filepath.Join(dir, "p"))
	if got, err := r.RealPath(link); err != nil || got != want {
		t.Fatalf("RealPath %q %v, want %q", got, err, want)
	}
}

// M2: an explicit base diffs from merge-base(HEAD, base) (three-dot), so
// work on the base branch this branch never touched is not judged.
func TestExplicitBaseIsThreeDot(t *testing.T) {
	needGit(t)
	ctx := context.Background()
	r := New()
	dir := t.TempDir()
	git(t, dir, "init", "-q")
	write(t, dir, "p/legacy.go", "package p\n\nfunc L() int { return 1 }\n")
	commitAll(t, dir, "base")
	before := git(t, dir, "rev-parse", "HEAD")
	git(t, dir, "checkout", "-q", "-b", "feat")
	write(t, dir, "p/f.go", "package p\n\nfunc F() int { return 2 }\n")
	commitAll(t, dir, "feat")
	// main moves on: it deletes legacy.go and adds other.go after feat branched.
	git(t, dir, "checkout", "-q", "main")
	git(t, dir, "rm", "-q", "p/legacy.go")
	write(t, dir, "p/other.go", "package p\n")
	commitAll(t, dir, "main work")
	git(t, dir, "checkout", "-q", "feat")

	for _, base := range []string{"main", before} { // a branch, and a push's before-SHA
		d, err := r.Diff(ctx, dir, base)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(d.Text, "+++ b/p/f.go") || strings.Contains(d.Text, "legacy.go") || strings.Contains(d.Text, "other.go") {
			t.Fatalf("base %s judged the base branch's work:\n%s", base, d.Text)
		}
		if want := base + " (merge-base " + before[:12] + ")"; d.Base != want {
			t.Fatalf("label %q want %q", d.Base, want)
		}
	}

	// No shared history: a clear error.
	git(t, dir, "checkout", "-q", "--orphan", "lonely")
	commitAll(t, dir, "orphan")
	if _, err := r.Diff(ctx, dir, "main"); err == nil || !strings.Contains(err.Error(), "no merge-base") {
		t.Fatal(err)
	}
}

// M3: the default base is the repo's real default branch.
func TestDefaultBranchDetection(t *testing.T) {
	needGit(t)
	ctx := context.Background()
	r := New()
	setup := func(branch string) (string, string) {
		dir := t.TempDir()
		git(t, dir, "init", "-q", "-b", branch)
		write(t, dir, "p/p.go", "package p\n")
		commitAll(t, dir, "base")
		fork := git(t, dir, "rev-parse", "HEAD")
		git(t, dir, "checkout", "-q", "-b", "feat")
		for _, f := range []string{"f1", "f2", "f3"} {
			write(t, dir, "p/"+f+".go", "package p\n")
			commitAll(t, dir, f)
		}
		return dir, fork
	}
	allThree := func(d gateDiff) bool {
		return strings.Contains(d.Text, "p/f1.go") && strings.Contains(d.Text, "p/f2.go") && strings.Contains(d.Text, "p/f3.go")
	}

	// A local master branch: every feature commit is judged, not just the last.
	dir, fork := setup("master")
	d, err := r.Diff(ctx, dir, "")
	if err != nil || !allThree(d) || d.Base != "master (merge-base "+fork[:12]+")" {
		t.Fatalf("%+v %v", d, err)
	}
	// origin/master beats local master.
	git(t, dir, "update-ref", "refs/remotes/origin/master", fork)
	if d, _ = r.Diff(ctx, dir, ""); !allThree(d) || !strings.HasPrefix(d.Base, "origin/master (merge-base ") {
		t.Fatalf("%+v", d)
	}
	// origin/HEAD names the default branch, whatever it is called.
	dir, fork = setup("develop")
	git(t, dir, "update-ref", "refs/remotes/origin/develop", fork)
	git(t, dir, "update-ref", "refs/remotes/origin/main", "HEAD") // a decoy that would hide f1..f3
	git(t, dir, "symbolic-ref", "refs/remotes/origin/HEAD", "refs/remotes/origin/develop")
	if d, _ = r.Diff(ctx, dir, ""); !allThree(d) || d.Base != "origin/develop (merge-base "+fork[:12]+")" {
		t.Fatalf("%+v", d)
	}
}
