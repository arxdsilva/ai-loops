// Package portfs writes generated platform packages and installer
// placements to disk (implements the CLI's PackageWriter).
package portfs

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/arxdsilva/ai-loops/internal/domain/plugin"
)

// Marker is the file every generated package root contains.
const Marker = ".loops-generated"

// fileSystem implements the CLI's PackageWriter.
type fileSystem struct{}

// New returns a fileSystem.
func New() *fileSystem { return &fileSystem{} }

// junk names are OS droppings ignored by Diff and removed by Write.
func junk(name string) bool {
	return name == ".DS_Store" || name == "Thumbs.db" || name == "desktop.ini" || strings.HasPrefix(name, "._")
}

// want validates files and returns them keyed by slash-clean relative path.
func want(files []plugin.File) (map[string]plugin.File, error) {
	m := make(map[string]plugin.File, len(files)+1)
	for _, f := range files {
		p := path.Clean(filepath.ToSlash(f.Path))
		if p == "." || path.IsAbs(p) || p == ".." || strings.HasPrefix(p, "../") {
			return nil, fmt.Errorf("portfs: unsafe package path %q", f.Path)
		}
		f.Path = p
		m[p] = f
	}
	if _, ok := m[Marker]; !ok {
		m[Marker] = plugin.File{Path: Marker, Data: []byte("generated by `loops port build`; do not edit\n")}
	}
	return m, nil
}

func sortedKeys(m map[string]plugin.File) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

// Write makes dir an exact image of files (plus the marker). It refuses a
// non-empty dir that lacks the marker.
func (fileSystem) Write(dir string, files []plugin.File) error {
	m, err := want(files)
	if err != nil {
		return err
	}
	ents, err := os.ReadDir(dir)
	switch {
	case errors.Is(err, fs.ErrNotExist):
	case err != nil:
		return err
	case len(ents) > 0:
		if _, err := os.Lstat(filepath.Join(dir, Marker)); err != nil {
			return fmt.Errorf("portfs: %s is not empty and has no %s marker; refusing to overwrite", dir, Marker)
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, rel := range sortedKeys(m) {
		if err := writeFile(dir, rel, m[rel]); err != nil {
			return err
		}
	}
	return prune(dir, m)
}

// writeFile writes one file atomically without following symlinks.
func writeFile(root, rel string, f plugin.File) error {
	parent := root
	if d := path.Dir(rel); d != "." {
		for _, part := range strings.Split(d, "/") {
			parent = filepath.Join(parent, part)
			fi, err := os.Lstat(parent)
			switch {
			case errors.Is(err, fs.ErrNotExist):
				if err := os.Mkdir(parent, 0o755); err != nil {
					return err
				}
			case err != nil:
				return err
			case fi.Mode()&fs.ModeSymlink != 0:
				if err := os.Remove(parent); err != nil {
					return err
				}
				if err := os.Mkdir(parent, 0o755); err != nil {
					return err
				}
			case !fi.IsDir():
				if err := os.Remove(parent); err != nil {
					return err
				}
				if err := os.Mkdir(parent, 0o755); err != nil {
					return err
				}
			}
		}
	}
	return atomicWrite(filepath.Join(root, filepath.FromSlash(rel)), f.Data, f.Exec)
}

func atomicWrite(dest string, data []byte, exec bool) error {
	if fi, err := os.Lstat(dest); err == nil && fi.IsDir() {
		if err := os.RemoveAll(dest); err != nil {
			return err
		}
	}
	tmp, err := os.CreateTemp(filepath.Dir(dest), ".loops-tmp-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	cleanup := func() { _ = os.Remove(name) }
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		cleanup()
		return err
	}
	if err := tmp.Close(); err != nil {
		cleanup()
		return err
	}
	mode := os.FileMode(0o644)
	if exec {
		mode = 0o755
	}
	if err := os.Chmod(name, mode); err != nil {
		cleanup()
		return err
	}
	if err := os.Rename(name, dest); err != nil {
		cleanup()
		return err
	}
	return nil
}

// prune removes files under dir not in m, then empty directories.
func prune(dir string, m map[string]plugin.File) error {
	var dirs []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if p == dir {
			return nil
		}
		rel, _ := filepath.Rel(dir, p)
		rel = filepath.ToSlash(rel)
		if d.Type()&fs.ModeSymlink == 0 && d.IsDir() {
			dirs = append(dirs, p)
			return nil
		}
		if _, ok := m[rel]; !ok {
			return os.Remove(p)
		}
		return nil
	})
	if err != nil {
		return err
	}
	for i := len(dirs) - 1; i >= 0; i-- {
		if ents, err := os.ReadDir(dirs[i]); err == nil && len(ents) == 0 {
			if err := os.Remove(dirs[i]); err != nil {
				return err
			}
		}
	}
	return nil
}

// Diff lists drifted relative paths (missing, extra, changed), sorted.
func (fileSystem) Diff(dir string, files []plugin.File) ([]string, error) {
	m, err := want(files)
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	var out []string
	err = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) && p == dir {
				return filepath.SkipAll
			}
			return err
		}
		if p == dir {
			return nil
		}
		if junk(d.Name()) {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			return nil
		}
		rel, _ := filepath.Rel(dir, p)
		rel = filepath.ToSlash(rel)
		seen[rel] = true
		f, ok := m[rel]
		if !ok {
			out = append(out, rel)
			return nil
		}
		fi, err := d.Info()
		if err != nil {
			return err
		}
		if !fi.Mode().IsRegular() {
			out = append(out, rel)
			return nil
		}
		got, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if !bytes.Equal(got, f.Data) || (fi.Mode()&0o111 != 0) != f.Exec {
			out = append(out, rel)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	for rel := range m {
		if !seen[rel] {
			out = append(out, rel)
		}
	}
	sort.Strings(out)
	return out, nil
}

// Place copies placements to their absolute destinations, skipping existing
// files unless force. A symlink at a destination is replaced, never written
// through.
func (fileSystem) Place(p []plugin.Placement, force bool) ([]string, error) {
	var written []string
	for _, pl := range p {
		if !filepath.IsAbs(pl.Dest) {
			return written, fmt.Errorf("portfs: destination %q is not absolute", pl.Dest)
		}
		if _, err := os.Lstat(pl.Dest); err == nil && !force {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(pl.Dest), 0o755); err != nil {
			return written, err
		}
		if err := atomicWrite(pl.Dest, pl.File.Data, pl.File.Exec); err != nil {
			return written, err
		}
		written = append(written, pl.Dest)
	}
	return written, nil
}
