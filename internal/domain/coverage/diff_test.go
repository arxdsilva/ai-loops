func TestParseDiff(t *testing.T) {
	got, err := ParseDiff(sampleDiff)
	if err != nil {
		t.Fatal(err)
	}
	want := Changes{
		"internal/x/a.go":        {Ranges: []LineRange{{4, 5}, {12, 12}}},
		"internal/y/new.go":      {Ranges: []LineRange{{1, 5}}, Added: true},
		"internal/z/new_name.go": {},
		"internal/w/moved.go":    {Ranges: []LineRange{{7, 9}}},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %+v", got)
	}
}

func TestParseDiffTricky(t *testing.T) {
	tests := []struct {
		name    string
		text    string
		want    Changes
		wantErr string
	}{
		{
			name: "CRLF",
			text: "diff --git a/a.go b/a.go\r\n--- a/a.go\r\n+++ b/a.go\r\n@@ -1 +1,2 @@\r\n-x\r\n+y\r\n+z\r\n",
			want: Changes{"a.go": {Ranges: []LineRange{{1, 2}}}},
		},
		{
			name: "content lines that look like headers are skipped",
			text: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -0,0 +1,3 @@\n+++ b/evil.go\n+@@ -1 +99,9 @@\n+--- a/x\n\\ No newline at end of file\n",
			want: Changes{"a.go": {Ranges: []LineRange{{1, 3}}}},
		},
		{
			name: "context lines count on both sides",
			text: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1,3 +1,4 @@\n ctx\n-old\n+new\n+new2\n ctx\n",
			want: Changes{"a.go": {Ranges: []LineRange{{1, 4}}}},
		},
		{
			name: "quoted path with a trailing tab",
			text: "diff --git \"a/my file.go\" \"b/my file.go\"\n--- \"a/my file.go\"\t\n+++ \"b/my file.go\"\t\n@@ -0,0 +1 @@\n+x\n",
			want: Changes{"my file.go": {Ranges: []LineRange{{1, 1}}}},
		},
		{
			name: "pure deletion hunk yields no range",
			text: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -4,2 +3,0 @@\n-x\n-y\n",
			want: Changes{"a.go": {}},
		},
		{name: "empty", text: "", want: Changes{}},
		{name: "bad hunk", text: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1 +x @@\n", wantErr: "line 4"},
		{name: "bad hunk header", text: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ nope\n", wantErr: "line 4"},
		{name: "bad old side", text: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -q +1 @@\n", wantErr: "line 4"},
		{name: "bad quoting", text: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ \"b/a.go\n", wantErr: "line 3"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := ParseDiff(tt.text)
			if tt.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("err %v want %q", err, tt.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(got, tt.want) {
				t.Fatalf("got %+v", got)
			}
		})
	}
}

func TestIsGenerated(t *testing.T) {
	tests := []struct {
		head string
		want bool
	}{
		{"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage x\n", true},
		{"// Copyright x\r\n\r\n// Code generated by stringer; DO NOT EDIT.\r\n\r\npackage x\r\n", true},
		{"package x\n\n// Code generated by hand. DO NOT EDIT.\n", false},           // must precede package
		{"// Code generated by x. Edit freely.\npackage x\n", false},                // no DO NOT EDIT
		{"// This says Code generated and DO NOT EDIT. inline\npackage x\n", false}, // wrong shape
		{"", false},
	}
	for _, tt := range tests {
		if got := IsGenerated(tt.head); got != tt.want {
			t.Errorf("%q: got %v", tt.head, got)
		}
	}
}
