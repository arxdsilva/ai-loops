// codexRoot is the plugin-root variable Codex expands in hook commands.
const codexRoot = "${PLUGIN_ROOT}"

// codexEvents are the canonical events Codex hooks support
// (learn.chatgpt.com/docs/hooks): PostToolUseFailure is not one of them.
var codexEvents = map[plugin.Event]bool{
	plugin.EventSessionStart:  true,
	plugin.EventPreToolUse:    true,
	plugin.EventPostToolUse:   true,
	plugin.EventSubagentStart: true,
	plugin.EventSubagentStop:  true,
	plugin.EventStop:          true,
}

// buildCodex emits platforms/codex/ (specs/PLATFORMS.md §3.2): an Agent
// Plugins 1.0 plugin.json with extensions["com.openai"].hooks, Claude-shaped
// hooks/hooks.json, agents/<role>.toml (installed by `loops install --target
// codex`, since plugins cannot bundle subagents) and README.md.
func buildCodex(p plugin.Plugin, src fs.FS, o Options) ([]plugin.File, []string, error) {
	files, err := baseFiles(p, src, plugin.Codex, o)
	if err != nil {
		return nil, nil, err
	}
	var warns []string

	manifest, err := jsonFile("plugin.json", codexManifest(p))
	if err != nil {
		return nil, nil, err
	}
	files = append(files, manifest)

	hooks, dropped := codexHooks(p)
	hf, err := jsonFile("hooks/hooks.json", map[string]any{"hooks": hooks})
	if err != nil {
		return nil, nil, err
	}
	files = append(files, hf)
	if len(dropped) > 0 {
		warns = append(warns, "codex: no "+strings.Join(dropped, ", ")+" event; failed tool calls are not traced")
	}

	var readOnly, allow []string
	for _, a := range p.Agents {
		files = append(files, plugin.File{Path: "agents/" + a.Name + ".toml", Data: []byte(codexAgent(a, o))})
		if a.ReadOnly {
			readOnly = append(readOnly, a.Name)
		}
		if len(a.Tools) > 0 {
			allow = append(allow, a.Name)
		}
	}
	if len(readOnly) > 0 {
		warns = append(warns, "codex: custom agents cannot restrict tools or sandbox; read-only is an instruction only for "+strings.Join(readOnly, ", "))
	}
	if len(allow) > 0 {
		warns = append(warns, "codex: tool allowlists dropped for "+strings.Join(allow, ", "))
	}

	files = append(files, plugin.File{Path: "README.md", Data: []byte(codexReadme(p, o))})
	sortFiles(files)
	return files, warns, nil
}

func codexManifest(p plugin.Plugin) map[string]any {
	m := map[string]any{
		"$schema":     "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
		"name":        p.Name,
		"version":     p.Version,
		"description": p.Description,
		"extensions": map[string]any{
			"com.openai": map[string]any{"hooks": "./hooks/hooks.json"},
		},
	}
	addMeta(m, p)
	return m
}

// addMeta sets the optional manifest metadata shared by the Codex and
// Cursor manifests.
func addMeta(m map[string]any, p plugin.Plugin) {
	if p.Author != "" {
		m["author"] = map[string]string{"name": p.Author}
	}
	if p.Homepage != "" {
		m["homepage"] = p.Homepage
	}
	if p.Repository != "" {
		m["repository"] = p.Repository
	}
	if p.License != "" {
		m["license"] = p.License
	}
	if len(p.Keywords) > 0 {
		m["keywords"] = p.Keywords
	}
}

type codexHandler struct {
	Type    string `json:"type"`
	Command string `json:"command"`
	Timeout int    `json:"timeout,omitempty"`
}

type codexGroup struct {
	Matcher string         `json:"matcher,omitempty"`
	Hooks   []codexHandler `json:"hooks"`
}

// codexHooks maps the canonical hooks to Codex's Claude-shaped config.
// Tool events match "*" (the binary filters by normalised tool name); the
// returned names are the events Codex lacks.
func codexHooks(p plugin.Plugin) (map[string][]codexGroup, []string) {
	out := map[string][]codexGroup{}
	var dropped []string
	byEvent := hooksByEvent(p.Hooks)
	for _, ev := range eventOrder {
		hs := byEvent[ev]
		if len(hs) == 0 {
			continue
		}
		if !codexEvents[ev] {
			dropped = append(dropped, string(ev))
			continue
		}
		for _, h := range hs {
			g := codexGroup{Hooks: []codexHandler{{Type: "command", Command: hookCommand(codexRoot, h.Name, plugin.Codex), Timeout: h.TimeoutSec}}}
			if ev == plugin.EventPreToolUse || ev == plugin.EventPostToolUse {
				g.Matcher = "*"
			}
			out[string(ev)] = append(out[string(ev)], g)
		}
	}
	return out, dropped
}

// codexAgent renders a Codex custom agent TOML file.
func codexAgent(a plugin.Agent, o Options) string {
	var b strings.Builder
	b.WriteString("# Generated by loops port build from agents/" + a.Name + ".md - do not edit.\n")
	b.WriteString("name = " + tomlString(a.Name) + "\n")
	b.WriteString("description = " + tomlString(a.Description) + "\n")
	if m := model(o, a.Tier); m != "" {
		b.WriteString("model = " + tomlString(m) + "\n")
	}
	body := a.Body
	if a.ReadOnly {
		body = readOnlyNote + "\n\n" + body
	}
	b.WriteString("developer_instructions = " + tomlMultiline(body) + "\n")
	return b.String()
}

func codexReadme(p plugin.Plugin, o Options) string {
	return fmt.Sprintf(`# %[1]s for Codex

Generated by `+"`loops port build`"+` from the canonical plugin (repository root). Do not edit; see specs/PLATFORMS.md §3.2.

## Install

1. Add the marketplace (the repository root holds `+"`.agents/plugins/marketplace.json`"+`, which points at `+"`platforms/codex`"+`):

       codex plugin marketplace add arxdsilva/ai-loops

2. Install the `+"`%[1]s`"+` plugin from the Plugins Directory (restart Codex after adding the marketplace).
3. Install the role agents (plugins cannot bundle subagents):

       loops install --target codex            # project: .codex/agents/
       loops install --target codex --scope user   # user: ~/.codex/agents/

4. Review and trust the plugin hooks with `+"`/hooks`"+`. Codex skips untrusted hooks, and re-asks when they change.

Commands are skills: `+"`$work`, `$init`, `$status`, `$report`"+`.

## Binary

`+"`bin/loops`"+` uses `+"`loops`"+` from PATH when it reports version %[2]s, else a cached binary, else downloads the prebuilt release binary for your OS/arch (checksum-verified, no Go needed). Only when no prebuilt binary exists does it fall back to `+"`go install %[3]s/cmd/loops@%[4]s`"+`.

## Caveats

- Hooks run only after you trust them, and plugins with hooks are not eligible for the public plugin directory.
- No PostToolUseFailure event: failed tool calls are not traced.
- Custom agents cannot restrict tools; read-only roles are told not to edit.
- Subagents cannot be resumed: loop-backs spawn a new agent of the same role (PLATFORMS §4, tier B).
- Models: roles inherit the session model unless `+"`loops port build --models <file.json>`"+` maps the tiers.
`, p.Name, strings.TrimPrefix(o.Version, "v"), o.Module, o.Version)
}

// codexMarketplace is the repo-root .agents/plugins/marketplace.json.
func codexMarketplace(p plugin.Plugin) plugin.File {
	f, _ := jsonFile(".agents/plugins/marketplace.json", map[string]any{
		"name":      "ai-loops",
		"interface": map[string]any{"displayName": "ai-loops"},
		"plugins": []any{map[string]any{
			"name":     p.Name,
			"source":   map[string]any{"source": "local", "path": "./platforms/codex"},
			"policy":   map[string]any{"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
			"category": "Productivity",
		}},
	})
	return f
}
