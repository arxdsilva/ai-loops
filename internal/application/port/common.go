// commandSkill reports whether a skill is also a user slash command.
func commandSkill(name string) bool {
	for _, c := range Commands {
		if c == name {
			return true
		}
	}
	return false
}

// sortFiles orders files by path (deterministic output).
func sortFiles(files []plugin.File) {
	sort.SliceStable(files, func(i, j int) bool { return files[i].Path < files[j].Path })
}

// putFile replaces the file at f.Path, or adds it, keeping files sorted.
func putFile(files []plugin.File, f plugin.File) []plugin.File {
	f.Path = path.Clean(f.Path)
	for i := range files {
		if files[i].Path == f.Path {
			files[i] = f
			return files
		}
	}
	files = append(files, f)
	sortFiles(files)
	return files
}

// jsonFile encodes v as indented JSON (two spaces, no HTML escaping,
// trailing newline). Map keys come out sorted, so output is deterministic.
func jsonFile(name string, v any) (plugin.File, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return plugin.File{}, fmt.Errorf("port: encode %s: %w", name, err)
	}
	return plugin.File{Path: name, Data: buf.Bytes()}, nil
}

// hookCommand is the hook command line for a generated package: the
// package shim under rootVar (e.g. "${PLUGIN_ROOT}"), the hook name and
// --platform.
func hookCommand(rootVar, name string, target plugin.Platform) string {
	return `"` + rootVar + `/bin/loops" hook ` + name + " --platform " + string(target)
}

// yamlString quotes s as a YAML double-quoted scalar (JSON escapes are a
// valid subset).
func yamlString(s string) string {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes
	return strings.TrimSuffix(buf.String(), "\n")
}

// tomlString quotes s as a TOML basic string.
func tomlString(s string) string {
	return `"` + tomlEscape(s, true) + `"`
}

// tomlMultiline quotes s as a TOML multi-line basic string ("""…"""),
// escaping backslashes, quote runs that would close it, and control
// characters other than newline and tab. The value always ends in a newline.
func tomlMultiline(s string) string {
	if !strings.HasSuffix(s, "\n") {
		s += "\n"
	}
	body := tomlEscape(s, false)
	body = strings.ReplaceAll(body, `"""`, `""\"`)
	return "\"\"\"\n" + body + `"""`
}

func tomlEscape(s string, quotes bool) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case r == '"' && quotes:
			b.WriteString(`\"`)
		case r == '\n' && quotes:
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteRune(r)
		case r == '\n':
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// hooksByEvent groups p.Hooks by event in canonical order, dropping
// repeated hook names within an event (emitters whose platform has no
// matchers collapse the matcher groups).
func hooksByEvent(hooks []plugin.Hook) map[plugin.Event][]plugin.Hook {
	out := map[plugin.Event][]plugin.Hook{}
	for _, h := range hooks {
		dup := false
		for _, x := range out[h.Event] {
			if x.Name == h.Name {
				dup = true
			}
		}
		if !dup {
			out[h.Event] = append(out[h.Event], h)
		}
	}
	return out
}

// skillByName returns the skill called name.
func skillByName(p plugin.Plugin, name string) (plugin.Skill, bool) {
	for _, s := range p.Skills {
		if s.Name == name {
			return s, true
		}
	}
	return plugin.Skill{}, false
}
