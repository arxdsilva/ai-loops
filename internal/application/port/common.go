// Shared emitter helpers. Worker P1 implements them; P2 uses them.

// DefaultModule is the Go module path package shims `go install` when
// Options.Module is empty.
const DefaultModule = "github.com/arxdsilva/ai-loops"

// withDefaults fills Options.Module (DefaultModule) and Options.Version
// ("v" + p.Version) when empty, and makes sure Version carries a "v".
func withDefaults(p plugin.Plugin, o Options) Options {
	if o.Module == "" {
		o.Module = DefaultModule
	}
	if o.Version == "" {
		o.Version = p.Version
	}
	if o.Version != "" && !strings.HasPrefix(o.Version, "v") {
		o.Version = "v" + o.Version
	}
	return o
}

// baseFiles returns what every generated package contains
// (specs/PLATFORMS.md §3): skills/ (skills/work/platforms/ filtered to
// <target>.md), specs/, templates/, ROLES.md, bin/loops (shim), and the
// .loops-generated marker (content: "generated by loops port build — do not
// edit; source: <module>@<version>\n").
func baseFiles(p plugin.Plugin, src fs.FS, target plugin.Platform, o Options) ([]plugin.File, error) {
	o = withDefaults(p, o)
	var files []plugin.File
	keep := func(name string) bool {
		const plat = "skills/work/platforms/"
		if strings.HasPrefix(name, plat) {
			return name == plat+string(target)+".md"
		}
		return true
	}
	for _, root := range []string{"skills", "specs", "templates"} {
		err := fs.WalkDir(src, root, func(name string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() || !keep(name) {
				return nil
			}
			data, err := fs.ReadFile(src, name)
			if err != nil {
				return err
			}
			files = append(files, plugin.File{Path: name, Data: data})
			return nil
		})
		if err != nil {
			if root != "skills" && errors.Is(err, fs.ErrNotExist) {
				continue
			}
			return nil, fmt.Errorf("port: copy %s: %w", root, err)
		}
	}
	// Every package carries the license: marketplaces install a package's
	// directory on its own, without the repository root.
	if data, err := fs.ReadFile(src, "LICENSE"); err == nil {
		files = append(files, plugin.File{Path: "LICENSE", Data: data})
	}
	if data, err := fs.ReadFile(src, "ROLES.md"); err == nil {
		files = append(files, plugin.File{Path: "ROLES.md", Data: data})
	} else if !errors.Is(err, fs.ErrNotExist) {
		return nil, fmt.Errorf("port: copy ROLES.md: %w", err)
	}
	files = append(files,
		shim(o),
		marker(o),
	)
	sortFiles(files)
	return files, nil
}

// marker is the .loops-generated file every package root carries (the
// package writer refuses to overwrite a directory without it).
func marker(o Options) plugin.File {
	return plugin.File{Path: ".loops-generated", Data: []byte("generated by loops port build — do not edit; source: " + o.Module + "@" + o.Version + "\n")}
}

// shim returns bin/loops for generated packages (PLATFORMS.md §6): a POSIX
// sh script that exports LOOPS_PLUGIN_ROOT (the package root), then resolves
// the binary for o.Version in this order: a non-script `loops` on PATH whose
// `loops version` matches, the cache, a checksum-verified download of the
// GitHub release asset (LOOPS_RELEASE_BASE overrides the host), and finally
// `go install <module>/cmd/loops@<version>` into the cache. Options are
// expected to be defaulted (withDefaults).
func shim(o Options) plugin.File {
	ver := strings.TrimPrefix(o.Version, "v")
	tag := "v" + ver
	script := `#!/bin/sh
# loops package shim (generated by loops port build - do not edit;
# specs/PLATFORMS.md §6). Runs the loops binary that matches this package:
# loops on PATH when its version matches, else the cache, else the release
# binary for this OS/arch (sha256-verified), else
# 'go install ` + o.Module + `/cmd/loops@` + tag + `' into the cache.
set -e
# Resolve symlinks to this script (relative targets are relative to the
# link's directory) so the package root is found from any link on PATH.
self=$0
while [ -h "$self" ]; do
  link=$(readlink "$self")
  case $link in
    /*) self=$link ;;
    *) self=$(dirname -- "$self")/$link ;;
  esac
done
root=$(CDPATH= cd -- "$(dirname -- "$self")/.." && pwd)
export LOOPS_PLUGIN_ROOT="$root"
V='` + ver + `'
module='` + o.Module + `'
tag='` + tag + `'
loops_base='https://` + o.Module + `/releases/download'
cache="${LOOPS_BIN_CACHE:-${CLAUDE_PLUGIN_DATA:-${PLUGIN_DATA:-${XDG_CACHE_HOME:-$HOME/.cache}/loops}}}"

` + shimLib + `
if loops_path || loops_cached; then
  exec "$bin" "$@"
fi
if loops_download; then
  exec "$bin" "$@"
fi
if command -v go >/dev/null 2>&1; then
  mkdir -p "$cache"
  tmp="$cache/.install-$$"
  rm -rf "$tmp"
  mkdir -p "$tmp"
  if ! GOBIN="$tmp" CGO_ENABLED=0 go install "$module/cmd/loops@$tag" >&2; then
    rm -rf "$tmp"
    echo "loops: go install $module/cmd/loops@$tag failed (the module must be reachable: public, or GOPRIVATE set)" >&2
    exit 1
  fi
  mv -f "$tmp/loops" "$cache/loops-$V"
  rm -rf "$tmp"
  loops_prune
  exec "$cache/loops-$V" "$@"
fi
echo "loops: no prebuilt binary for ${os:-$(uname -s)}/${arch:-$(uname -m)} v$V and no Go toolchain; see https://github.com/arxdsilva/ai-loops#install" >&2
exit 1
`
	return plugin.File{Path: "bin/loops", Data: []byte(script), Exec: true}
}

// readOnlyNote opens the body of a read-only role on platforms that cannot
// enforce it per agent (or whose switch would also block the role's own
// run-dir file): the role still writes research/*.md, plan.v*.md, qa/*.md,
// proofs/ or reflection.md.
const readOnlyNote = "You are a read-only role: you may write only your own file under the run dir (the one your brief names); never edit repo code."

// contextText returns templates/PLUGIN_CONTEXT.md (the always-on plugin
// context for rules files such as GEMINI.md and Cursor rules).
func contextText(src fs.FS) string {
	data, err := fs.ReadFile(src, "templates/PLUGIN_CONTEXT.md")
	if err != nil {
		return ""
	}
	return string(data)
}

