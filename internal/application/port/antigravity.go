// antigravityEvents are the canonical hook events supported by Google
// Antigravity (hooks.json / .agents/hooks.json / ~/.gemini/config/hooks.json).
var antigravityEvents = map[plugin.Event]bool{
	plugin.EventSessionStart: true,
	plugin.EventPreToolUse:   true,
	plugin.EventPostToolUse:  true,
	plugin.EventStop:         true,
}

// antigravityMatcherEvents are the Antigravity hook events that wrap
// handlers in a tool matcher object.
var antigravityMatcherEvents = map[plugin.Event]bool{
	plugin.EventPreToolUse:  true,
	plugin.EventPostToolUse: true,
}

// antigravityTools maps canonical Claude Code tool names to Antigravity tool
// names for hooks.json PreToolUse/PostToolUse matchers.
var antigravityTools = map[string]string{
	"Read":      "view_file",
	"Bash":      "run_command",
	"Edit":      "replace_file_content",
	"MultiEdit": "multi_replace_file_content",
	"Write":     "write_to_file",
	"Agent":     "invoke_subagent",
	"Task":      "invoke_subagent",
}

