type antigravityHandler struct {
	Type    string `json:"type"`
	Command string `json:"command"`
	Timeout int    `json:"timeout,omitempty"`
}

type antigravityMatcherGroup struct {
	Matcher string               `json:"matcher,omitempty"`
	Hooks   []antigravityHandler `json:"hooks"`
}

// buildAntigravity emits platforms/antigravity/ (specs/PLATFORMS.md §3.6).
func buildAntigravity(p plugin.Plugin, src fs.FS, o Options) ([]plugin.File, []string, error) {
	files, err := baseFiles(p, src, plugin.Antigravity, o)
	if err != nil {
		return nil, nil, err
	}
	manifest, err := jsonFile("plugin.json", antigravityManifest(p))
	if err != nil {
		return nil, nil, err
	}
	hooksFile, err := jsonFile("hooks.json", antigravityHooks(p))
	if err != nil {
		return nil, nil, err
	}
	agentFiles, agentWarns := antigravityAgents(p, o)
	ctx := contextText(src)

	files = append(files, manifest, hooksFile,
		plugin.File{Path: "rules/AGENTS.md", Data: []byte(ctx)},
		plugin.File{Path: "README.md", Data: []byte(antigravityReadme)},
	)
	files = append(files, agentFiles...)
	sortFiles(files)

	return files, antigravityWarnings(p, ctx, agentWarns), nil
}

func antigravityManifest(p plugin.Plugin) map[string]any {
	m := map[string]any{
		"$schema":     "https://antigravity.google/schemas/v1/plugin.json",
		"name":        p.Name,
		"displayName": "loops",
		"version":     p.Version,
		"description": p.Description,
	}
	if p.Author != "" {
		m["author"] = map[string]string{"name": p.Author}
	}
	if p.Homepage != "" {
		m["homepage"] = p.Homepage
	}
	if p.License != "" {
		m["license"] = p.License
	}
	if len(p.Keywords) > 0 {
		m["keywords"] = p.Keywords
	}
	return m
}

func antigravityAgents(p plugin.Plugin, o Options) ([]plugin.File, []string) {
	files := make([]plugin.File, 0, len(p.Agents))
	var readOnly []string
	for _, a := range p.Agents {
		files = append(files, antigravityAgent(a, o))
		if a.ReadOnly {
			readOnly = append(readOnly, a.Name)
		}
	}
	var warns []string
	if len(readOnly) > 0 {
		warns = append(warns, "antigravity: read-only roles omit replace_file_content and enforce write_to_file run-dir scoping via write-guard (run_command remains instruction-enforced) for "+strings.Join(readOnly, ", "))
	}
	return files, warns
}

func antigravityAgentTools(a plugin.Agent) []string {
	switch {
	case a.Name == "hardware-researcher":
		return []string{"run_command", "send_message"}
	case a.Name == "web-researcher":
		return []string{"view_file", "write_to_file", "run_command", "grep_search", "find_by_name", "list_dir", "send_message", "search_web"}
	case a.ReadOnly:
		return []string{"view_file", "write_to_file", "run_command", "grep_search", "find_by_name", "list_dir", "send_message"}
	default:
		return []string{"view_file", "write_to_file", "replace_file_content", "run_command", "grep_search", "find_by_name", "list_dir", "send_message"}
	}
}

func antigravityAgent(a plugin.Agent, o Options) plugin.File {
	body := a.Body
	if a.ReadOnly {
		body = readOnlyNote + "\n\n" + body
	}
	m := model(o, a.Tier)
	if m == "" {
		m = "inherit"
	}
	content := "---\n" +
		"name: " + a.Name + "\n" +
		"description: " + yamlString(a.Description) + "\n" +
		"subagent: true\n" +
		"mainAgent: false\n" +
		"model: " + yamlString(m) + "\n" +
		"tools: [" + strings.Join(antigravityAgentTools(a), ", ") + "]\n" +
		"commandExecutionPolicy: \"auto\"\n" +
		"---\n\n" + body
	return plugin.File{Path: "agents/" + a.Name + ".md", Data: []byte(content)}
}

func antigravityHooks(p plugin.Plugin) map[string]any {
	hooks := map[string]any{"enabled": true}
	byEvent := hooksByEvent(p.Hooks)
	for _, ev := range eventOrder {
		hs := byEvent[ev]
		if !antigravityEvents[ev] || len(hs) == 0 {
			continue
		}
		if ev == plugin.EventPreToolUse {
			hs = withAntigravityWriteGuard(hs)
		}
		if antigravityMatcherEvents[ev] {
			hooks[string(ev)] = antigravityMatcherGroups(hs)
		} else {
			hooks[string(ev)] = antigravityFlatHandlers(hs)
		}
	}
	return map[string]any{"loops": hooks}
}

func withAntigravityWriteGuard(hs []plugin.Hook) []plugin.Hook {
	for _, h := range hs {
		if h.Name == "write-guard" {
			return hs
		}
	}
	return append(hs[:len(hs):len(hs)], plugin.Hook{
		Event:      plugin.EventPreToolUse,
		Matcher:    "Edit|Write|MultiEdit",
		Name:       "write-guard",
		TimeoutSec: 10,
	})
}

func antigravityFlatHandlers(hs []plugin.Hook) []antigravityHandler {
	out := make([]antigravityHandler, 0, len(hs))
	for _, h := range hs {
		out = append(out, antigravityHandler{
			Type:    "command",
			Command: "./bin/loops hook " + h.Name + " --platform antigravity",
			Timeout: h.TimeoutSec,
		})
	}
	return out
}

func antigravityMatcherGroups(hs []plugin.Hook) []antigravityMatcherGroup {
	out := make([]antigravityMatcherGroup, 0, len(hs))
	for _, h := range hs {
		out = append(out, antigravityMatcherGroup{
			Matcher: antigravityMatcher(h.Matcher),
			Hooks: []antigravityHandler{{
				Type:    "command",
				Command: "./bin/loops hook " + h.Name + " --platform antigravity",
				Timeout: h.TimeoutSec,
			}},
		})
	}
	return out
}

func antigravityMatcher(m string) string {
	if m == "" || m == "*" {
		return ""
	}
	parts := strings.Split(m, "|")
	out := make([]string, 0, len(parts))
	seen := make(map[string]bool, len(parts))
	for _, raw := range parts {
		tok := mapAntigravityToken(raw)
		if tok == "*" {
			return ""
		}
		if tok != "" && !seen[tok] {
			seen[tok] = true
			out = append(out, tok)
		}
	}
	return strings.Join(out, "|")
}

func mapAntigravityToken(raw string) string {
	tok := strings.TrimSpace(raw)
	if mapped, ok := antigravityTools[tok]; ok {
		return mapped
	}
	return tok
}

func antigravityWarnings(p plugin.Plugin, ctx string, agentWarns []string) []string {
	var warns []string
	for _, e := range []plugin.Event{plugin.EventPostToolUseFailure, plugin.EventSubagentStart, plugin.EventSubagentStop} {
		if hasEvent(p, e) {
			warns = append(warns, fmt.Sprintf("antigravity: %s has no Antigravity event; its hooks are dropped", e))
		}
	}
	if strings.TrimSpace(ctx) == "" {
		warns = append(warns, "antigravity: templates/PLUGIN_CONTEXT.md is empty; rules/AGENTS.md has no plugin context")
	}
	warns = append(warns, agentWarns...)
	warns = append(warns,
		"antigravity: hook commands use ./bin/loops (plugin root cwd for agy plugin install) and are rewritten to the plugin-home shim by `loops install`",
		"antigravity: slash commands are the skills themselves (no command files)",
	)
	return warns
}
