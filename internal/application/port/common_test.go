func TestShim(t *testing.T) {
	f := shim(Options{Module: "example.com/m", Version: "v1.2.3"})
	s := string(f.Data)
	if f.Path != "bin/loops" || !f.Exec {
		t.Fatalf("shim file = %s exec=%v", f.Path, f.Exec)
	}
	for _, want := range []string{
		"#!/bin/sh\n",
		`export LOOPS_PLUGIN_ROOT="$root"`,
		`while [ -h "$self" ]; do`,
		`link=$(readlink "$self")`,
		`*) self=$(dirname -- "$self")/$link ;;`,
		`root=$(CDPATH= cd -- "$(dirname -- "$self")/.." && pwd)`,
		"V='1.2.3'",
		`version 2>/dev/null`,
		`cache="${LOOPS_BIN_CACHE:-${CLAUDE_PLUGIN_DATA:-${PLUGIN_DATA:-${XDG_CACHE_HOME:-$HOME/.cache}/loops}}}"`,
		"loops_base='https://example.com/m/releases/download'",
		`${LOOPS_RELEASE_BASE:-$loops_base}/v$V`,
		"loops-$os-$arch$ext",
		"checksums.txt",
		"LOOPS_SKIP_VERIFY",
		"shasum -a 256",
		"curl -fsSL --retry 2",
		"loops_download",
		"module='example.com/m'",
		"tag='v1.2.3'",
		`GOBIN="$tmp" CGO_ENABLED=0 go install "$module/cmd/loops@$tag"`,
		`mv -f "$tmp/loops" "$cache/loops-$V"`,
		"command -v go",
		"no prebuilt binary for",
		"and no Go toolchain; see https://github.com/arxdsilva/ai-loops/blob/main/docs/GUIDE.md#install",
		`exec "$bin" "$@"`,
	} {
		if !strings.Contains(s, want) {
			t.Errorf("shim lacks %q", want)
		}
	}
	if !strings.Contains(s, shimLib) {
		t.Error("shim lacks the shared lib block")
	}
	// LOOPS_PLUGIN_ROOT is exported before any loops runs.
	if strings.Index(s, "export LOOPS_PLUGIN_ROOT") > strings.Index(s, `"$c" version`) {
		t.Error("LOOPS_PLUGIN_ROOT exported after the PATH probe")
	}
}

