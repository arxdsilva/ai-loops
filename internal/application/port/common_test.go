func TestWithDefaults(t *testing.T) {
	p := plugin.Plugin{Version: "0.2.0"}
	o := withDefaults(p, Options{})
	if o.Module != DefaultModule || o.Version != "v0.2.0" {
		t.Fatalf("defaults = %+v", o)
	}
	o = withDefaults(p, Options{Module: "example.com/m", Version: "1.0.0"})
	if o.Module != "example.com/m" || o.Version != "v1.0.0" {
		t.Fatalf("explicit = %+v", o)
	}
	if o := withDefaults(p, Options{Version: "v3.1.0"}); o.Version != "v3.1.0" {
		t.Fatalf("v kept = %q", o.Version)
	}
}

func TestBaseFiles(t *testing.T) {
	p, src := loadFixture(t)
	files, err := baseFiles(p, src, plugin.Codex, Options{})
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	for _, f := range files {
		paths = append(paths, f.Path)
	}
	want := []string{
		".loops-generated", "ROLES.md", "bin/loops",
		"skills/init/SKILL.md", "skills/report/SKILL.md", "skills/status/SKILL.md",
		"skills/testing/SKILL.md", "skills/testing/ref/extra.md",
		"skills/work/SKILL.md", "skills/work/platforms/codex.md",
		"specs/WORKFLOW.md", "templates/CLAIMS_REPORT.md", "templates/PLUGIN_CONTEXT.md",
	}
	if strings.Join(paths, "\n") != strings.Join(want, "\n") {
		t.Fatalf("paths =\n%s\nwant\n%s", strings.Join(paths, "\n"), strings.Join(want, "\n"))
	}
	for _, f := range files {
		switch f.Path {
		case ".loops-generated":
			if string(f.Data) != "generated by loops port build — do not edit; source: github.com/arxdsilva/ai-loops@v0.2.0\n" {
				t.Errorf("marker = %q", f.Data)
			}
		case "bin/loops":
			if !f.Exec {
				t.Error("shim not executable")
			}
		case "skills/work/SKILL.md":
			if !bytes.Equal(f.Data, src["skills/work/SKILL.md"].Data) || f.Exec {
				t.Error("skill not copied unchanged")
			}
		}
	}
}

